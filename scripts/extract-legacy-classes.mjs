#!/usr/bin/env node
/**
 * Regenerate `codemods/0.2/legacy-classes.json`: every class name the 0.1
 * components styled, grouped by the component directory that owned it.
 *
 * The 0.1 sources no longer exist on this branch, so point the script at a
 * checkout of the last 0.1 release:
 *
 *   git archive v0.1.0-alpha.23 src | tar -x -C /tmp/uc-0.1
 *   node scripts/extract-legacy-classes.mjs /tmp/uc-0.1 v0.1.0-alpha.23
 *
 * `ui-common upgrade` reports consumer selectors, DOM queries and tests that
 * target these names. Astryx does not render them.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import postcss from "postcss";
import selectorParser from "postcss-selector-parser";
import { globSync } from "tinyglobby";

const [, , checkout, revision = "unknown"] = process.argv;
if (!checkout) {
  console.error("usage: extract-legacy-classes.mjs <0.1 checkout> [revision]");
  process.exit(2);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = globSync("src/components/**/*.css", { cwd: checkout, absolute: true });

/** @type {Record<string, Set<string>>} */
const byComponent = {};

for (const file of files.sort()) {
  const component = relative(resolve(checkout, "src/components"), file).split(sep)[0];
  const set = (byComponent[component] ??= new Set());
  const ast = postcss.parse(await readFile(file, "utf8"), { from: file });
  ast.walkRules((rule) => {
    // Keyframe steps are rules too, and have no classes.
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    selectorParser((selectors) => {
      selectors.walkClasses((node) => {
        set.add(node.value);
      });
    }).processSync(rule.selector);
  });
}

const out = {
  $comment:
    "Generated by scripts/extract-legacy-classes.mjs from the 0.1 component stylesheets. Do not edit.",
  source: revision,
  components: Object.fromEntries(
    Object.entries(byComponent)
      .filter(([, set]) => set.size > 0)
      .map(([name, set]) => [name, [...set].sort()]),
  ),
};

await writeFile(
  resolve(root, "codemods/0.2/legacy-classes.json"),
  `${JSON.stringify(out, null, 2)}\n`,
);
console.log(
  `Wrote ${Object.values(out.components).flat().length} class names from ${files.length} stylesheet(s).`,
);
